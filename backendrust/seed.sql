-- ---------------------------------------------------------------------------
-- Transactions: 90 days of realistic spend + payroll on the 5th + subs on 1/11/21.
-- Generated with a CTE so we can keep the script short.
-- ---------------------------------------------------------------------------
WITH params AS (
  SELECT generate_series(0, 89) AS d, NOW() AS now_ts
),
days AS (
  SELECT d, now_ts - (d || ' days')::interval AS day
  FROM params
),
food AS (
  SELECT 'Hotpot Hound' AS m UNION ALL SELECT 'Daily Bread' UNION ALL SELECT 'Lanzhou Noodles'
  UNION ALL SELECT 'Starbucks' UNION ALL SELECT 'Family Mart' UNION ALL SELECT 'Panda Wok'
),
transport AS (
  SELECT 'Didi' AS m UNION ALL SELECT 'Metro Card Top-up' UNION ALL SELECT 'Shell Gas'
),
subs AS (
  SELECT 'NetStream Premium' AS m, 4500 AS amt UNION ALL SELECT 'CloudVault 100GB', 1500
  UNION ALL SELECT 'FitCoach Pro', 2900 UNION ALL SELECT 'MusicPass Family', 2000
),
misc AS (
  SELECT 'Taobao' AS m UNION ALL SELECT 'JD Books' UNION ALL SELECT 'Apple Store' UNION ALL SELECT 'IKEA'
)
INSERT INTO transactions (id, account_id, amount_fen, direction, category, merchant, memo, occurred_at, status)
SELECT
  'tx_' || a.id || '_' || d.d || '_' || ROW_NUMBER() OVER (PARTITION BY a.id, d.d ORDER BY random()),
  a.id,
  amt,
  dir,
  cat,
  merchant,
  '',
  ts,
  'posted'
FROM (
  VALUES
    ('acc_demo_chk',   'u_demo'),
    ('acc_intl_chk',   'u_intl'),
    ('acc_locked_chk', 'u_locked')
) AS a(id, owner)
CROSS JOIN days d
CROSS JOIN LATERAL (
  -- 1–3 food hits
  SELECT
    (random() * 6000 + 2000)::bigint * -1               AS amt,
    'debit'                                              AS dir,
    'food'                                               AS cat,
    (SELECT m FROM food ORDER BY random() LIMIT 1)       AS merchant,
    (d.day::timestamp + (7 + (random() * 15)::int) * interval '1 hour' + (random() * 60)::int * interval '1 minute') AS ts
  FROM generate_series(1, 1 + (random() * 2)::int)
  UNION ALL
  -- occasional transport
  SELECT
    (ARRAY[1500,2800,4500,6000])[1 + (random() * 3)::int]::bigint * -1,
    'debit','transport',
    (SELECT m FROM transport ORDER BY random() LIMIT 1),
    d.day::timestamp + (7 + (random() * 16)::int) * interval '1 hour' + (random() * 60)::int * interval '1 minute'
  WHERE random() < 0.4
  UNION ALL
  -- monthly payroll on the 5th
  SELECT 1_500_000, 'credit', 'income', 'Acme Corp Payroll',
         d.day::timestamp + interval '9 hours'
  WHERE EXTRACT(DAY FROM d.day) = 5
  UNION ALL
  -- subscriptions on 1/11/21
  SELECT -s.amt, 'debit', 'subscription', s.m,
         d.day::timestamp + interval '3 hours' + interval '15 minutes'
  FROM subs s
  WHERE EXTRACT(DAY FROM d.day) IN (1, 11, 21) AND random() < 0.55
  UNION ALL
  -- misc shopping
  SELECT (random() * 100000 + 20000)::bigint * -1, 'debit', 'shopping',
         (SELECT m FROM misc ORDER BY random() LIMIT 1),
         d.day::timestamp + (10 + (random() * 13)::int) * interval '1 hour' + (random() * 60)::int * interval '1 minute'
  WHERE random() < 0.04
) g;

